'use client';
// 자동생성 팝업 (PRD §8): 강의 선택 → 이름 목록 각 행에 긴 주소 입력 → 전체 생성
import { useEffect, useRef, useState } from 'react';
import Link from 'next/link';
import { useRouter } from 'next/navigation';
import { apiFetch, ApiError, newIdempotencyKey } from '@/lib/client/api';
import { DuplicateDialog, type DuplicateReview } from './DuplicateDialog';
import { CopyButton } from './CopyButton';

interface Course { id: string; name: string; instructor_name: string | null }
interface TemplateItem { id: string; name: string; sort_order: number; destination_slots: string[] | null }
interface Template { id: string; display_name: string; version: number; items: TemplateItem[] }

// 입력 키: 기본(0번) 주소는 항목 ID, 전환 주소 1번 이후는 "항목ID#번호"
const slotKey = (id: string, pos: number) => (pos === 0 ? id : `${id}#${pos}`);
interface BatchResult {
  id: string; total_count: number; template_version: number; created_at: string; course_id: string;
  results: { template_item_id: string; link_id: string; name: string; short_url: string; destination_url: string }[];
}

export function AutoGenerateButton({ courses }: { courses: Course[] }) {
  const [open, setOpen] = useState(false);
  return (
    <>
      <button type="button" className="button secondary" onClick={() => setOpen(true)}>자동생성</button>
      {open && <AutoGenerateDialog courses={courses} onClose={() => setOpen(false)} />}
    </>
  );
}

function AutoGenerateDialog({ courses, onClose }: { courses: Course[]; onClose: () => void }) {
  const router = useRouter();
  const [courseId, setCourseId] = useState(courses.length === 1 ? courses[0].id : '');
  const [tpl, setTpl] = useState<Template | null>(null);
  const [loading, setLoading] = useState(false);
  const [urls, setUrls] = useState<Record<string, string>>({});
  const [renamed, setRenamed] = useState<Record<string, { before: string; confirmed: boolean }>>({});
  const [notice, setNotice] = useState<string | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [rowErrors, setRowErrors] = useState<Record<string, string>>({});
  const [busy, setBusy] = useState(false);
  const [review, setReview] = useState<{ data: DuplicateReview; changed: boolean } | null>(null);
  const [result, setResult] = useState<BatchResult | null>(null);
  const pending = useRef<{ payload: string; key: string } | null>(null);

  async function loadTemplate(prev: Template | null) {
    setLoading(true);
    setError(null);
    try {
      const r = await apiFetch<{ data: Template | null }>('/internal/generation-template');
      const t = r.body.data;
      if (!t || t.items.length === 0) {
        setTpl(null);
        setError('자동생성할 이름 목록을 먼저 등록해 주세요.');
        return;
      }
      if (prev) {
        // 항목 ID 기준으로 입력 보존, 명칭이 바뀐 행은 주소 재확인 필요 (§7.3)
        const prevById = new Map(prev.items.map((i) => [i.id, i.name]));
        const nextRenamed: typeof renamed = {};
        for (const i of t.items) {
          const before = prevById.get(i.id);
          if (before !== undefined && before !== i.name && urls[i.id]) nextRenamed[i.id] = { before, confirmed: false };
        }
        const removed = prev.items.filter((i) => !t.items.some((x) => x.id === i.id)).map((i) => i.name);
        const added = t.items.filter((i) => !prevById.has(i.id)).length;
        setRenamed(nextRenamed);
        setNotice([
          '이름 목록이 변경되었습니다. 입력값을 확인한 뒤 다시 진행해 주세요.',
          removed.length ? `제외된 항목: ${removed.join(', ')}` : '',
          added ? `새 항목 ${added}개는 주소를 입력해야 합니다.` : '',
        ].filter(Boolean).join(' '));
      }
      setTpl(t);
    } catch (e) {
      setError(e instanceof ApiError ? e.message : '이름 목록을 불러오지 못했습니다.');
    } finally {
      setLoading(false);
    }
  }

  useEffect(() => {
    void loadTemplate(null);
    // 최초 1회만 불러온다
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, []);

  async function submit(extra: Record<string, string> = {}) {
    if (!tpl) return;
    const errs: Record<string, string> = {};
    for (const i of tpl.items) {
      if (!urls[i.id]?.trim()) errs[i.id] = i.destination_slots
        ? `'${i.destination_slots[0]}' 주소는 기본 연결이라 꼭 입력해야 합니다.`
        : '해당 행의 전체 주소를 입력해 주세요.';
      else if (renamed[i.id] && !renamed[i.id].confirmed) errs[i.id] = '명칭이 바뀌었습니다. 주소를 확인해 주세요.';
    }
    setRowErrors(errs);
    if (Object.keys(errs).length || !courseId) {
      setError(!courseId ? '강의를 선택해 주세요.' : '입력이 필요한 행이 있습니다.');
      return;
    }
    const body = {
      course_id: courseId,
      template_id: tpl.id,
      template_version: tpl.version,
      items: tpl.items.map((i) => (i.destination_slots
        ? {
            template_item_id: i.id,
            slot_urls: i.destination_slots.map((_, pos) => urls[slotKey(i.id, pos)]?.trim() || null),
          }
        : { template_item_id: i.id, destination_url: urls[i.id].trim() })),
      ...extra,
    };
    const payload = JSON.stringify(body);
    const key = pending.current?.payload === payload ? pending.current.key : newIdempotencyKey();
    pending.current = { payload, key };
    setBusy(true);
    setError(null);
    try {
      const r = await apiFetch<{ data: BatchResult }>('/internal/link-batches', { method: 'POST', body, idempotencyKey: key, timeoutMs: 45000 });
      pending.current = null;
      setReview(null);
      setResult(r.body.data);
      router.refresh();
    } catch (e) {
      if (!(e instanceof ApiError)) throw e;
      if (e.code !== 'NETWORK_ERROR' && e.code !== 'IDEMPOTENCY_IN_PROGRESS' && e.status < 500) pending.current = null;
      if (e.code === 'DUPLICATE_DESTINATION' || e.code === 'DUPLICATE_REVIEW_CHANGED') {
        setReview({ data: e.details as unknown as DuplicateReview, changed: e.code === 'DUPLICATE_REVIEW_CHANGED' });
        return;
      }
      setReview(null);
      if (e.code === 'TEMPLATE_CHANGED') {
        await loadTemplate(tpl);
        return;
      }
      const re: Record<string, string> = {};
      for (const r of e.rowErrors ?? []) if (r.template_item_id) re[r.template_item_id] = r.message;
      setRowErrors(re);
      setError(e.code === 'NETWORK_ERROR'
        ? '응답을 받지 못했습니다. 입력을 바꾸지 말고 같은 내용으로 다시 시도해 주세요.'
        : e.message);
    } finally {
      setBusy(false);
    }
  }

  const course = courses.find((c) => c.id === (result?.course_id ?? courseId));

  return (
    <div className="modal-backdrop" role="dialog" aria-modal="true">
      <div className="modal wide">
        {result ? (
          <>
            <h2>✓ {result.total_count}개의 짧은 주소를 생성했습니다</h2>
            <p className="muted">강의 {course?.name} · 목록 버전 {result.template_version}</p>
            <div className="modal-scroll">
              <table className="table small">
                <thead><tr><th>명칭</th><th>긴 주소</th><th>짧은 주소</th></tr></thead>
                <tbody>
                  {result.results.map((r) => (
                    <tr key={r.link_id}>
                      <td>{r.name}</td>
                      <td className="ellipsis" title={r.destination_url}>{r.destination_url}</td>
                      <td>{r.short_url} <CopyButton text={r.short_url} /></td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
            <div className="modal-actions">
              <Link className="button secondary" href={`/links?generation_batch_id=${result.id}`} onClick={onClose}>목록에서 보기</Link>
              <button className="button" type="button" onClick={onClose}>닫기</button>
            </div>
          </>
        ) : (
          <>
            <h2>자동생성</h2>
            <div className="row">
              <label>
                강의{' '}
                <select value={courseId} onChange={(e) => setCourseId(e.target.value)} disabled={busy}>
                  <option value="" disabled>진행중 강의 선택</option>
                  {courses.map((c) => <option key={c.id} value={c.id}>{c.name}</option>)}
                </select>
              </label>
              {tpl && <span className="muted">{tpl.display_name} · 버전 {tpl.version} · {tpl.items.length}개 생성</span>}
            </div>
            {courses.length === 0 && <p className="error">최고관리자가 진행중 강의를 등록해야 합니다.</p>}
            {notice && <p className="warn" role="status">{notice}</p>}
            {loading && <p className="muted">이름 목록을 불러오는 중…</p>}
            {tpl && (
              <div className="modal-scroll">
                <table className="table small">
                  <thead><tr><th>번호</th><th>명칭</th><th>긴 주소</th><th>상태</th></tr></thead>
                  <tbody>
                    {tpl.items.map((i, idx) => (
                      <tr key={i.id}>
                        <td>{idx + 1}</td>
                        <td>
                          {i.name}
                          {renamed[i.id] && <div className="warn">이전 명칭: {renamed[i.id].before}</div>}
                        </td>
                        <td>
                          {(i.destination_slots ?? [null]).map((label, pos) => {
                            const key = slotKey(i.id, pos);
                            const input = (
                              <input
                                className="full"
                                value={urls[key] ?? ''}
                                onChange={(e) => {
                                  setUrls({ ...urls, [key]: e.target.value });
                                  if (pos === 0 && rowErrors[i.id]) {
                                    const { [i.id]: _cleared, ...rest } = rowErrors;
                                    void _cleared;
                                    setRowErrors(rest);
                                  }
                                  if (renamed[i.id]) setRenamed({ ...renamed, [i.id]: { ...renamed[i.id], confirmed: false } });
                                }}
                                placeholder="https://"
                                disabled={busy}
                                aria-label={label ? `${i.name} - ${label}` : `${i.name} 긴 주소`}
                              />
                            );
                            if (label === null) return <span key={pos}>{input}</span>;
                            return (
                              <div key={pos} className="slot-inputs" style={{ marginBottom: '0.375rem' }}>
                                <label>
                                  <span>
                                    {pos === 0 ? <strong>{label}</strong> : label}
                                    <span className="sub">{pos === 0 ? '기본 연결 · 필수' : '나중에 입력 가능'}</span>
                                  </span>
                                  {input}
                                </label>
                              </div>
                            );
                          })}
                          {renamed[i.id] && (
                            <label className="inline">
                              <input
                                type="checkbox"
                                checked={renamed[i.id].confirmed}
                                onChange={(e) => setRenamed({ ...renamed, [i.id]: { ...renamed[i.id], confirmed: e.target.checked } })}
                              />{' '}
                              주소 확인 완료
                            </label>
                          )}
                        </td>
                        <td>
                          {rowErrors[i.id]
                            ? <span className="error">{rowErrors[i.id]}</span>
                            : urls[i.id]?.trim() ? <span className="pill on">정상</span> : <span className="pill off plain">입력 필요</span>}
                        </td>
                      </tr>
                    ))}
                  </tbody>
                </table>
              </div>
            )}
            {error && <p className="error">{error}</p>}
            {busy && <p className="muted">{tpl?.items.length}개 링크를 생성하고 있습니다. 창을 닫아도 서버 작업은 취소되지 않습니다.</p>}
            <div className="modal-actions">
              {!busy && <button className="button secondary" type="button" onClick={onClose}>취소</button>}
              <button className="button" type="button" disabled={!tpl || busy || !courseId} onClick={() => void submit()}>
                {busy && <span className="spinner" aria-hidden="true" />}{busy ? '처리 중…' : `${tpl?.items.length ?? 0}개 생성하기`}
              </button>
            </div>
          </>
        )}
      </div>
      {review && (
        <DuplicateDialog
          review={review.data}
          changed={review.changed}
          busy={busy}
          onCancel={() => setReview(null)}
          onCreate={() => void submit({ review_token: review.data.review_token, duplicate_decision: 'create_new' })}
        />
      )}
    </div>
  );
}
